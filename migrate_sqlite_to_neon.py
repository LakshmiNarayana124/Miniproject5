
import os
import re
import sqlite3
import sys
from pathlib import Path

import psycopg
from psycopg import sql

ROOT = Path(__file__).resolve().parent
SQLITE_DB = ROOT / "Backend" / "database" / "intelliwatch.db"

# Parent tables must be created before tables that reference them.
TABLE_ORDER = [
    "users",
    "firebase_identities",
    "machine_assessments",
    "ml_models",
    "unknown_patterns",
    "edge_devices",
    "sensor_readings",
    "sensor_analytics",
    "anomaly_events",
    "recommendations",
    "machine_config",
    "knowledge_profiles",
    "engine_observations",
    "analysis_events",
    "sensor_knowledge_profiles",
    "sensor_status_history",
    "system_status_history",
    "verified_labels",
    "accuracy_trend",
    "audit_entries",
    "control_signal_queue",
    "explorer_history",
    "threshold_definitions",
    "control_signals",
    "user_permissions",
    "admin_promotion_requests",
    "account_recovery_requests",
    "auth_security_tokens",
    "auth_rate_limits",
]

def stop(message):
    print(f"\nMIGRATION STOPPED: {message}")
    sys.exit(1)

def quote_identifier(name):
    return '"' + name.replace('"', '""') + '"'

def convert_sqlite_ddl(ddl):
    # Convert SQLite auto-increment primary keys to PostgreSQL identity keys.
    ddl = re.sub(
        r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b",
        "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        ddl,
        flags=re.IGNORECASE,
    )

    # All remaining SQLite INTEGER columns become PostgreSQL BIGINT.
    ddl = re.sub(r"\bINTEGER\b", "BIGINT", ddl, flags=re.IGNORECASE)

    # SQLite's NOCASE collation is not a PostgreSQL collation.
    ddl = re.sub(r"\s+COLLATE\s+NOCASE\b", "", ddl, flags=re.IGNORECASE)

    return ddl

def main():
    database_url = os.environ.get("NEON_DIRECT_URL")

    if not database_url:
        stop("Set the NEON_DIRECT_URL environment variable first.")

    if not SQLITE_DB.exists():
        stop(f"SQLite database not found: {SQLITE_DB}")

    if "sslmode=require" not in database_url.lower():
        print("WARNING: Confirm that your Neon connection uses SSL.")

    print("Checking original SQLite database...")

    sqlite_conn = sqlite3.connect(str(SQLITE_DB))
    sqlite_conn.row_factory = sqlite3.Row

    integrity = sqlite_conn.execute("PRAGMA integrity_check").fetchone()[0]
    if integrity != "ok":
        stop(f"SQLite integrity check failed: {integrity}")

    foreign_key_errors = sqlite_conn.execute(
        "PRAGMA foreign_key_check"
    ).fetchall()

    if foreign_key_errors:
        stop(f"SQLite foreign-key errors found: {foreign_key_errors[:5]}")

    existing_tables = {
        row["name"]
        for row in sqlite_conn.execute("""
            SELECT name
            FROM sqlite_master
            WHERE type = 'table'
              AND name NOT LIKE 'sqlite_%'
        """)
    }

    missing = set(TABLE_ORDER) - existing_tables
    if missing:
        stop(f"Expected tables missing from SQLite: {sorted(missing)}")

    print("SQLite integrity: OK")
    print(f"SQLite tables found: {len(existing_tables)}")

    source_counts = {}
    for table in TABLE_ORDER:
        source_counts[table] = sqlite_conn.execute(
            f"SELECT COUNT(*) FROM {quote_identifier(table)}"
        ).fetchone()[0]

    print(f"SQLite records found: {sum(source_counts.values())}")

    print("\nConnecting to Neon PostgreSQL...")

    try:
        pg_conn = psycopg.connect(database_url)
    except Exception as exc:
        stop(f"Could not connect to Neon: {exc}")

    try:
        with pg_conn.cursor() as cur:
            cur.execute("""
                SELECT COUNT(*)
                FROM information_schema.tables
                WHERE table_schema = 'public'
                  AND table_type = 'BASE TABLE'
            """)
            existing_count = cur.fetchone()[0]

            if existing_count:
                stop(
                    "Neon public schema is not empty. "
                    "No tables or data were changed. "
                    "Use a fresh Neon database/schema for this migration."
                )

        print("Neon target is empty: OK")
        print("\nCreating PostgreSQL tables...")

        with pg_conn.transaction():
            with pg_conn.cursor() as cur:

                # Create all tables in dependency order.
                for table in TABLE_ORDER:
                    row = sqlite_conn.execute(
                        """
                        SELECT sql
                        FROM sqlite_master
                        WHERE type = 'table' AND name = ?
                        """,
                        (table,),
                    ).fetchone()

                    if not row or not row["sql"]:
                        raise RuntimeError(
                            f"Could not retrieve CREATE TABLE for {table}"
                        )

                    ddl = convert_sqlite_ddl(row["sql"])
                    cur.execute(ddl)
                    print(f"  Created: {table}")

                print("\nCopying records...")

                for table in TABLE_ORDER:
                    columns = [
                        row["name"]
                        for row in sqlite_conn.execute(
                            f"PRAGMA table_info({quote_identifier(table)})"
                        )
                    ]

                    column_sql = sql.SQL(", ").join(
                        sql.Identifier(column) for column in columns
                    )

                    placeholders = sql.SQL(", ").join(
                        sql.Placeholder() for _ in columns
                    )

                    insert_query = sql.SQL(
                        "INSERT INTO {} ({}) VALUES ({})"
                    ).format(
                        sql.Identifier(table),
                        column_sql,
                        placeholders,
                    )

                    rows = sqlite_conn.execute(
                        f"SELECT * FROM {quote_identifier(table)}"
                    ).fetchall()

                    if rows:
                        cur.executemany(
                            insert_query,
                            [tuple(row[column] for column in columns)
                             for row in rows],
                        )

                    print(f"  {table}: {len(rows)} records copied")

                print("\nRecreating indexes...")

                indexes = sqlite_conn.execute("""
                    SELECT name, sql
                    FROM sqlite_master
                    WHERE type = 'index'
                      AND sql IS NOT NULL
                    ORDER BY name
                """).fetchall()

                for index in indexes:
                    cur.execute(convert_sqlite_ddl(index["sql"]))
                    print(f"  Created index: {index['name']}")

                # Preserve SQLite's case-insensitive username uniqueness.
                cur.execute("""
                    CREATE UNIQUE INDEX uq_users_username_lower
                    ON users (LOWER(username))
                """)

                print("\nResetting identity sequences...")

                for table in TABLE_ORDER:
                    pk_columns = sqlite_conn.execute(
                        f"PRAGMA table_info({quote_identifier(table)})"
                    ).fetchall()

                    identity_columns = [
                        row["name"]
                        for row in pk_columns
                        if row["pk"] == 1
                        and "AUTOINCREMENT" in (
                            sqlite_conn.execute(
                                """
                                SELECT sql FROM sqlite_master
                                WHERE type = 'table' AND name = ?
                                """,
                                (table,),
                            ).fetchone()["sql"].upper()
                        )
                    ]

                    for column in identity_columns:
                        cur.execute(
                            sql.SQL("""
                                SELECT setval(
                                    pg_get_serial_sequence(%s, %s),
                                    GREATEST(COALESCE(MAX({}), 1), 1),
                                    COUNT(*) > 0
                                )
                                FROM {}
                            """).format(
                                sql.Identifier(column),
                                sql.Identifier(table),
                            ),
                            (f"public.{table}", column),
                        )

        print("\nVerifying migrated record counts...")

        mismatches = []

        with pg_conn.cursor() as cur:
            for table in TABLE_ORDER:
                cur.execute(
                    sql.SQL("SELECT COUNT(*) FROM {}").format(
                        sql.Identifier(table)
                    )
                )
                target_count = cur.fetchone()[0]
                source_count = source_counts[table]

                print(
                    f"  {table}: SQLite={source_count}, "
                    f"Neon={target_count}"
                )

                if source_count != target_count:
                    mismatches.append(
                        (table, source_count, target_count)
                    )

            cur.execute("""
                SELECT COUNT(*)
                FROM information_schema.tables
                WHERE table_schema = 'public'
                  AND table_type = 'BASE TABLE'
            """)
            target_tables = cur.fetchone()[0]

        if mismatches:
            stop(f"Record count mismatches: {mismatches}")

        if target_tables != len(TABLE_ORDER):
            stop(
                f"Expected {len(TABLE_ORDER)} tables, "
                f"found {target_tables} in Neon."
            )

        print("\n" + "=" * 55)
        print("DATABASE MIGRATION SUCCESSFUL")
        print("=" * 55)
        print(f"Tables migrated: {len(TABLE_ORDER)}")
        print(f"Records migrated: {sum(source_counts.values())}")
        print("Record counts: MATCHED")
        print("SQLite integrity: OK")
        print("Original SQLite database: UNCHANGED")
        print("Neon PostgreSQL: VERIFIED")

    except Exception as exc:
        pg_conn.rollback()
        print("\nMigration failed. PostgreSQL transaction rolled back.")
        print(f"Reason: {exc}")
        raise

    finally:
        pg_conn.close()
        sqlite_conn.close()

if __name__ == "__main__":
    main()
